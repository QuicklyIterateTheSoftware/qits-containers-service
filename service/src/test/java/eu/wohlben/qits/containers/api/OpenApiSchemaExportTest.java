package eu.wohlben.qits.containers.api;

import static io.restassured.RestAssured.given;

import io.quarkus.test.junit.QuarkusTest;
import io.quarkus.test.junit.TestProfile;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import org.eclipse.microprofile.config.inject.ConfigProperty;
import org.junit.jupiter.api.Test;

/**
 * Writes {@code docs/openapi.yml} as a side effect of the suite, the same way the monorepo's own
 * {@code OpenApiSchemaExportTest} does (qits-1923). Checking the document in is what turns an API
 * change into a reviewable diff instead of something a caller discovers at runtime, and it is the
 * document the platform coverage check (qits-1940) reads.
 *
 * <p>This is a test only because {@code @QuarkusTest} is the cheapest way to stand the application
 * up and read its own {@code /containers/q/openapi}. It asserts nothing — the assertion is the diff.
 *
 * <p>{@code @TestProfile(FakeDriverProfile.class)}, because the default profile wires a real docker
 * driver: this test only needs the application to boot and serve its own schema, not a daemon.
 *
 * <p>The test classpath is indexed too, so any {@code @Path} resource under {@code src/test} would
 * land in the committed document unless it is {@code @Operation(hidden = true)} — this module has
 * none today. The tunnel's WebSocket ({@code TunnelControlSocket}) and its raw Vert.x route ({@code
 * TunnelStreamRoute}) are not JAX-RS and appear in no document.
 *
 * <p>{@code info.version} in the written document is pinned to {@code 0} by {@code
 * quarkus.smallrye-openapi.info-version} in the test properties, so the file changes only with the
 * API, not with each release.
 */
@QuarkusTest
@TestProfile(FakeDriverProfile.class)
public class OpenApiSchemaExportTest {

  /**
   * Where the document is served from. Read rather than written literally: {@code /containers/q/*}
   * is outside {@code quarkus.rest.path} and moves only with this key, so a hard-coded
   * {@code /containers/q/openapi} would simply 404 the day the service's segment changed — and this
   * test asserts nothing else, so the 404 is the only thing that would tell you.
   */
  @ConfigProperty(name = "quarkus.http.non-application-root-path")
  String nonApplicationRootPath;

  @Test
  public void exportOpenApiSchema() throws Exception {
    String schema =
        given()
            .when()
            .get(nonApplicationRootPath + "/openapi")
            .then()
            .statusCode(200)
            .extract()
            .asString();

    Path docsDir = Paths.get("../docs");
    if (!Files.exists(docsDir)) {
      Files.createDirectories(docsDir);
    }

    String header =
        "# THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.\n"
            + "# Run `./mvnw -pl service test -Dtest=OpenApiSchemaExportTest` to regenerate.\n";

    Files.writeString(docsDir.resolve("openapi.yml"), header + schema);
  }
}
