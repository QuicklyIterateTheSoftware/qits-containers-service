import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * {@link PrivateEdgeResolver} against a scripted docker CLI and a resolv.conf in a temp directory —
 * every fallback the class javadoc promises, and the one shape it resolves to.
 *
 * <p>The script answers by the argv's first three words and records every argv it was handed, so
 * a test can say not only what the spec became but which questions were asked: the "network is
 * missing" case asks nothing further, which is the property that keeps a missing overlay from ever
 * becoming a join the driver would unwind.
 */
class PrivateEdgeResolverTest {

  private static final String NETWORK_ID = "4k2x9q7m1n0p3r5s6t8u";

  private static final String SERVICE_ID = "y8w2v6b4c1d3";

  private static final String VIPS =
      "[{\"NetworkID\":\"ingressid0001\",\"Addr\":\"10.0.0.7/24\"},"
          + "{\"NetworkID\":\"" + NETWORK_ID + "\",\"Addr\":\"10.231.0.5/20\"}]";

  private static final String RESOLV_CONF =
      """
      # Generated by Docker Engine.
      # This file can be edited; Docker Engine will not make further changes once it
      # has been modified.

      nameserver 127.0.0.11
      options ndots:0

      # Based on host file: '/etc/resolv.conf' (internal resolver)
      # ExtServers: [192.168.1.1 not-an-address host(9.9.9.9)]
      # Overrides: []
      # Option ndots from: internal
      """;

  @TempDir Path dir;

  private Path resolvConf;

  private final Map<String, ContainerProcess.Result> answers = new LinkedHashMap<>();

  private final List<List<String>> calls = new ArrayList<>();

  @BeforeEach
  void host() throws IOException {
    resolvConf = dir.resolve("resolv.conf");
    Files.writeString(resolvConf, RESOLV_CONF);
    answer("network inspect", 0, NETWORK_ID + "\n");
    answer("service ls", 0, SERVICE_ID + "\n");
    answer("service inspect", 0, VIPS + "\n");
  }

  private void answer(String verb, int exit, String output) {
    answers.put(verb, new ContainerProcess.Result(exit, output, false, false));
  }

  private PrivateEdgeResolver resolver() {
    return new PrivateEdgeResolver(
        "docker",
        "qits-private",
        "qits-edge-private",
        resolvConf,
        (List<String> argv, Duration timeout, int maxChars) -> {
          calls.add(argv);
          assertEquals(ContainersTimeouts.INSPECT, timeout, "every call carries the timeout");
          assertEquals(ContainersTimeouts.SHORT_MAX_CHARS, maxChars, "every call carries a bound");
          ContainerProcess.Result result = answers.get(argv.get(1) + " " + argv.get(2));
          return result == null ? new ContainerProcess.Result(1, "unscripted", false, false) : result;
        });
  }

  private static ContainerSpec spec() {
    return ContainerSpec.builder("registry.qits.wohlben.eu/qits/qits-workspace-base:1")
        .network("qits-net")
        .build();
  }

  @Test
  void theOverlayAndTheEdgeFoundAreAJoinAndTheVipAheadOfTheHostsOwnServers() {
    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    // host(9.9.9.9) is kept as 9.9.9.9 and the token that is no address is skipped, order kept.
    assertEquals(List.of("10.231.0.5", "192.168.1.1", "9.9.9.9"), resolved.dns());
    assertEquals("qits-net", resolved.network(), "the primary network is untouched");
    assertEquals(
        List.of(
            List.of("docker", "network", "inspect", "--format", "{{.Id}}", "qits-private"),
            List.of(
                "docker",
                "service",
                "ls",
                "-q",
                "--filter",
                "label=qits.platform.deployments.app-name=qits-edge-private"),
            List.of(
                "docker",
                "service",
                "inspect",
                "--format",
                "{{json .Endpoint.VirtualIPs}}",
                SERVICE_ID)),
        calls);
  }

  @Test
  void theStartupLineSaysWhatAFlaggedContainerWouldGetAndAsksNothingElse() {
    assertEquals(
        "a privateEdge container on this host would join qits-private ("
            + NETWORK_ID
            + ") with resolvers [10.231.0.5, 192.168.1.1, 9.9.9.9]: edge VIP 10.231.0.5, upstreams"
            + " [192.168.1.1, 9.9.9.9]",
        resolver().logResolution());
    assertEquals(3, calls.size(), "the same three questions a run asks: " + calls);
  }

  @Test
  void theStartupLineOnAHostWithNoOverlay() {
    answer("network inspect", 1, "Error response from daemon: network qits-private not found\n");

    assertEquals(
        "a privateEdge container on this host would run as asked: no qits-private network",
        resolver().logResolution());
  }

  @Test
  void aHostWithNoOverlayAddsNothingAtAllAndAsksNothingFurther() {
    answer("network inspect", 1, "Error response from daemon: network qits-private not found\n");

    ContainerSpec asked = spec();
    assertSame(asked, resolver().resolve(asked, "qits-ws-1"));
    assertEquals(1, calls.size(), "no service lookup for a network that is not there: " + calls);
  }

  @Test
  void aDaemonThatDidNotAnswerTheInspectIsTreatedAsNoOverlay() {
    answers.put("network inspect", new ContainerProcess.Result(-1, "", true, false));

    ContainerSpec asked = spec();
    assertSame(asked, resolver().resolve(asked, "qits-ws-1"));
  }

  @Test
  void noExtServersLineIsAJoinWithTheHostsResolvers() throws IOException {
    Files.writeString(resolvConf, "nameserver 127.0.0.11\noptions ndots:0\n");

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    assertEquals(List.of(), resolved.dns(), "never a VIP-only resolver list");
  }

  @Test
  void anUnreadableResolvConfIsAJoinWithTheHostsResolvers() throws IOException {
    Files.delete(resolvConf);

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    assertEquals(List.of(), resolved.dns());
  }

  @Test
  void noEdgeServiceIsAJoinWithTheHostsResolvers() {
    answer("service ls", 0, "");

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    assertEquals(List.of(), resolved.dns());
    assertEquals(2, calls.size(), "no service inspect without a service: " + calls);
  }

  @Test
  void twoEdgeServicesAreAJoinWithTheHostsResolvers() {
    answer("service ls", 0, SERVICE_ID + "\nz9z9z9z9z9z9\n");

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    assertEquals(List.of(), resolved.dns());
  }

  @Test
  void aServiceListingDockerRefusedIsAJoinWithTheHostsResolvers() {
    // A worker node, or a daemon not in a swarm, refuses `service ls` outright.
    answer("service ls", 1, "Error response from daemon: This node is not a swarm manager.\n");

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    assertEquals(List.of(), resolved.dns());
  }

  @Test
  void anEdgeWithNoVipOnTheOverlayIsAJoinWithTheHostsResolvers() {
    answer("service inspect", 0, "[{\"NetworkID\":\"ingressid0001\",\"Addr\":\"10.0.0.7/24\"}]\n");

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("qits-private"), resolved.extraNetworks());
    assertEquals(List.of(), resolved.dns());
  }

  @Test
  void aLoopbackUpstreamReachedFromTheHostIsKeptAsItsAddress() throws IOException {
    Files.writeString(resolvConf, "nameserver 127.0.0.11\n# ExtServers: [host(127.0.0.53)]\n");

    ContainerSpec resolved = resolver().resolve(spec(), "qits-ws-1");

    assertEquals(List.of("10.231.0.5", "127.0.0.53"), resolved.dns());
  }

  @Test
  void aSpecAlreadyOnTheOverlayIsNotJoinedToItAgainButStillGetsTheResolver() {
    ContainerSpec onIt = ContainerSpec.builder("alpine:3").network("qits-private").build();

    ContainerSpec resolved = resolver().resolve(onIt, "qits-ws-1");

    assertEquals(List.of(), resolved.extraNetworks());
    assertEquals(List.of("10.231.0.5", "192.168.1.1", "9.9.9.9"), resolved.dns());
  }

  @Test
  void everythingElseOnTheSpecIsCarriedThroughUnchanged() {
    ContainerSpec asked =
        ContainerSpec.builder("alpine:3")
            .network("qits-net")
            .env("TOKEN", "secret")
            .label("qits.workspace", "1")
            .mount("qits_ws_1_workspace", "/workspace")
            .hostDockerSocket(true)
            .name("qits-ws-1")
            .user("1000")
            .init(true)
            .build();

    ContainerSpec resolved = resolver().resolve(asked, "qits-ws-1");

    assertEquals(
        ContainerSpec.builder("alpine:3")
            .network("qits-net")
            .env("TOKEN", "secret")
            .label("qits.workspace", "1")
            .mount("qits_ws_1_workspace", "/workspace")
            .hostDockerSocket(true)
            .name("qits-ws-1")
            .user("1000")
            .init(true)
            .dns("10.231.0.5", "192.168.1.1", "9.9.9.9")
            .extraNetwork("qits-private")
            .build(),
        resolved);
  }

  // --- staleness (qits-2231) ------------------------------------------------------------------------

  /** The edge recreated onto a new VIP: the scripted service now answers 10.231.0.212. */
  private void edgeMovedTo(String vip) {
    answer(
        "service inspect",
        0,
        "[{\"NetworkID\":\"" + NETWORK_ID + "\",\"Addr\":\"" + vip + "/20\"}]\n");
  }

  /** The container's own inspect: its recorded Dns, then the networks it is attached to. */
  private void container(String dnsJson, String... networks) {
    answer("container inspect", 0, dnsJson + " " + String.join(" ", networks) + " \n");
  }

  @Test
  void aContainerStillOnTheVipTheEdgeLeftIsStale() {
    container("[\"10.231.0.2\",\"192.168.1.1\"]", "qits-net", "qits-private");
    edgeMovedTo("10.231.0.212");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertTrue(staleness.onPrivateEdge());
    assertEquals(List.of("10.231.0.2", "192.168.1.1"), staleness.dns());
    assertEquals(List.of("10.231.0.212", "192.168.1.1", "9.9.9.9"), staleness.expected());
    assertTrue(staleness.stale());
    assertNull(staleness.detail());
    assertEquals(
        List.of(
            "docker",
            "container",
            "inspect",
            "--format",
            "{{json .HostConfig.Dns}} {{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}",
            "qits-ws-1"),
        calls.getFirst(),
        "one inspect of the container, through the same guarded seam");
  }

  @Test
  void aContainerWhoseFirstResolverIsTheEdgesIsNotStaleWhateverFollowsIt() {
    // Upstream-only differences are not stale: the first resolver is the one the edge is reached on.
    container("[\"10.231.0.5\",\"1.1.1.1\"]", "qits-net", "qits-private");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertTrue(staleness.onPrivateEdge());
    assertEquals(List.of("10.231.0.5", "192.168.1.1", "9.9.9.9"), staleness.expected());
    assertFalse(staleness.stale());
  }

  @Test
  void aContainerOffTheOverlayIsNotStaleAndTheEdgeIsNotAsked() {
    container("[]", "qits-net");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertFalse(staleness.onPrivateEdge());
    assertEquals(List.of(), staleness.dns());
    assertEquals(List.of(), staleness.expected());
    assertFalse(staleness.stale());
    assertEquals(1, calls.size(), "no network, service or resolv.conf question: " + calls);
  }

  @Test
  void noEdgeVipMeansNoChoiceAndNothingStale() {
    container("[\"10.231.0.2\",\"192.168.1.1\"]", "qits-private");
    answer("service ls", 0, "");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertTrue(staleness.onPrivateEdge());
    assertEquals(List.of(), staleness.expected());
    assertFalse(staleness.stale());
  }

  @Test
  void noUpstreamMeansNoChoiceAndNothingStale() throws IOException {
    container("[\"10.231.0.2\",\"192.168.1.1\"]", "qits-private");
    edgeMovedTo("10.231.0.212");
    Files.writeString(resolvConf, "nameserver 127.0.0.11\n");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertEquals(List.of(), staleness.expected());
    assertFalse(staleness.stale());
  }

  @Test
  void aContainerJoinedWithTheHostsResolversIsStaleOnceAChoiceExists() {
    // Run while the edge had no VIP (or no upstream line), so docker recorded no Dns at all.
    container("[]", "qits-net", "qits-private");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertTrue(staleness.onPrivateEdge());
    assertEquals(List.of(), staleness.dns());
    assertEquals(List.of("10.231.0.5", "192.168.1.1", "9.9.9.9"), staleness.expected());
    assertTrue(staleness.stale());
  }

  @Test
  void aNullDnsIsTheEmptyList() {
    container("null", "qits-private");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertEquals(List.of(), staleness.dns());
    assertTrue(staleness.stale());
  }

  @Test
  void anInspectDockerRefusedIsNotStaleAndSaysWhy() {
    answer("container inspect", 1, "Error response from daemon: No such object: qits-ws-1\n");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertFalse(staleness.onPrivateEdge());
    assertFalse(staleness.stale());
    assertTrue(staleness.detail().contains("No such object"), staleness.detail());
    assertEquals(1, calls.size(), calls.toString());
  }

  @Test
  void anInspectThatTimedOutIsNotStaleAndSaysWhy() {
    answers.put("container inspect", new ContainerProcess.Result(-1, "", true, false));

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertFalse(staleness.stale());
    assertTrue(staleness.detail().contains("did not answer"), staleness.detail());
  }

  @Test
  void anUnreadableInspectIsNotStaleAndSaysWhy() {
    answer("container inspect", 0, "<no value> qits-private\n");

    PrivateEdgeResolver.Staleness staleness = resolver().staleness("qits-ws-1");

    assertFalse(staleness.stale());
    assertNotNull(staleness.detail());
  }

  @Test
  void theChoiceIsTheResolutionARunWouldMake() {
    assertEquals(List.of("10.231.0.5", "192.168.1.1", "9.9.9.9"), resolver().choice());
    answer("network inspect", 1, "Error response from daemon: network qits-private not found\n");
    assertEquals(List.of(), resolver().choice());
  }

  @Test
  void theExtServersLineIsReadAsDockerWritesIt() {
    assertEquals(List.of(), PrivateEdgeResolver.extServers("# ExtServers: []\n"));
    assertEquals(
        List.of("1.1.1.1", "2606:4700:4700::1111"),
        PrivateEdgeResolver.extServers("# ExtServers: [1.1.1.1 host(2606:4700:4700::1111) 1.1.1.1]"));
    assertTrue(PrivateEdgeResolver.extServers("nameserver 8.8.8.8\n").isEmpty());
  }
}
